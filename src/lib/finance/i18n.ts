const DICTS: Record<Language, Dict> = { en, fr, pt };

export function translate(lang: Language, key: string, params?: Record<string, string | number>): string {
  let s = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return s;
}

export function useT() {
  const { state } = useFinance();
  return (key: string, params?: Record<string, string | number>) => translate(state.language, key, params);
}

export function useLanguage(): Language {
  return useFinance().state.language;
}

export function useLocale(): string {
  return LOCALE[useFinance().state.language];
}

const MONTH_EN_TO_INDEX: Record<string, number> = {
  Jan: 0, Feb: 1, Mar: 2, Apr: 3, May: 4, Jun: 5,
  Jul: 6, Aug: 7, Sep: 8, Oct: 9, Nov: 10, Dec: 11,
};

const MONTH_CACHE: Partial<Record<Language, string[]>> = {};
function monthsShort(lang: Language): string[] {
  if (!MONTH_CACHE[lang]) {
    const fmt = new Intl.DateTimeFormat(LOCALE[lang], { month: "short" });
    MONTH_CACHE[lang] = Array.from({ length: 12 }, (_, i) =>
      fmt.format(new Date(2024, i, 1)).replace(/\.$/, ""),
    );
  }
  return MONTH_CACHE[lang]!;
}

export function tMonthShort(lang: Language, shortEn: string): string {
  const idx = MONTH_EN_TO_INDEX[shortEn];
  if (idx === undefined) return shortEn;
  const m = monthsShort(lang)[idx];
  return m.charAt(0).toUpperCase() + m.slice(1);
}

export function useMonthShort() {
  const lang = useLanguage();
  return (shortEn: string) => tMonthShort(lang, shortEn);
}

export function formatDateLocalized(
  iso: string | Date,
  lang: Language,
  style: "short" | "long" | "longTime" = "short",
): string {
  const d = typeof iso === "string" ? parseISO(iso) : iso;
  const locale = LOCALE[lang];
  const opts: Intl.DateTimeFormatOptions =
    style === "short"
      ? { day: "2-digit", month: "short" }
      : style === "long"
        ? { day: "2-digit", month: "short", year: "numeric" }
        : { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" };
  return new Intl.DateTimeFormat(locale, opts).format(d);
}

export function useFormatDate() {
  const lang = useLanguage();
  return (iso: string | Date, style?: "short" | "long" | "longTime") =>
    formatDateLocalized(iso, lang, style);
}

export function useDistanceToNow() {
  const lang = useLanguage();
  return (iso: string) =>
    fdtn(parseISO(iso), { addSuffix: true, locale: DATE_FNS_LOCALE[lang] });
}
